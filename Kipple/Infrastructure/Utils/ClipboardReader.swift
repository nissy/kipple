import AppKit
import ApplicationServices
import Combine
import libxml2

/// All programmatic reads share one attempt per clipboard revision and access policy.
@MainActor
final class ClipboardReader: ObservableObject {
    struct Stamp: Equatable, Sendable {
        let changeCount: Int
        let accessRevision: UInt64
    }

    struct Snapshot: Sendable {
        let stamp: Stamp
        let text: String?
        let richText: ClipboardRichText?
        let sourceURI: String?
        let chromiumSourceURL: URL?
        let htmlByItem: [Data?]
        var source: Source?
        let hasSourceDeclaration: Bool
        let shouldExcludeFromHistory: Bool
    }

    struct Source: Sendable {
        let name: String?
        let bundleID: String?
        let processID: Int32?
        let windowTitle: String?
    }

    struct Selection: Sendable {
        let text: String
        let source: Source
        let webPageURL: URL?
        var imageURLs: [URL]?
    }

    private struct FocusedSelection: Sendable {
        let text: String
        let title: String?
        let webPageURL: URL?
        let imageURLs: [URL]?
    }

    static let shared = ClipboardReader(readSelection: readForegroundSelection)
    private static let chromeBundleID = "com.google.Chrome"
    private static let sourceBundleType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let chromiumSourceType = NSPasteboard.PasteboardType("org.chromium.source-url")
    private static let historyExcludedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    ]
    private static let webArchiveTypes = [
        NSPasteboard.PasteboardType("com.apple.webarchive"),
        NSPasteboard.PasteboardType("Apple Web Archive pasteboard type")
    ]

    @Published private(set) var accessBehavior: NSPasteboard.AccessBehavior
    @Published private(set) var readFailed = false
    private let pasteboard: NSPasteboard
    private let readAccess: () -> NSPasteboard.AccessBehavior
    private let readText: () -> String?
    private let readSelection: (@MainActor (Int, URL?) async -> Selection?)?
    private var accessRevision: UInt64 = 0
    private var cached: Snapshot?
    private var failedAttempt: Stamp?

    init(
        pasteboard: NSPasteboard = .general,
        readAccess: (() -> NSPasteboard.AccessBehavior)? = nil,
        readText: (() -> String?)? = nil,
        readSelection: (@MainActor (Int, URL?) async -> Selection?)? = nil
    ) {
        self.pasteboard = pasteboard
        self.readAccess = readAccess ?? { pasteboard.accessBehavior }
        self.readText = readText ?? { pasteboard.string(forType: .string) }
        self.readSelection = readSelection
        accessBehavior = self.readAccess()
    }

    var observation: Stamp {
        refreshAccess()
        return Stamp(changeCount: pasteboard.changeCount, accessRevision: accessRevision)
    }

    func refreshAccess() {
        let behavior = readAccess()
        guard behavior != accessBehavior else { return }
        accessBehavior = behavior
        invalidate()
        SystemDiagnostics.clipboard(policy: behavior, readFailed: false)
    }

    /// A retry is explicit user intent; polling never repeatedly asks for the same content.
    func read(retry: Bool = false) -> Snapshot? {
        if retry { invalidate() }
        let stamp = observation
        guard accessBehavior != .alwaysDeny else { return nil }
        if let cached, cached.stamp == stamp { return cached }
        guard failedAttempt != stamp else { return nil }

        let text = readText()
        let richText = text.flatMap { ClipboardRichText(pasteboard: pasteboard, text: $0) }
        let types = pasteboard.types
        let items = text == nil ? [] : pasteboard.pasteboardItems ?? []
        let sourceURI = readCommonSourceURI(from: items)
        let chromiumSourceURL = items.count == 1 ? items.first?.string(forType: Self.chromiumSourceType)
            .flatMap { URL(string: $0, encodingInvalidCharacters: false) } : nil
        let htmlByItem = richText?.items.map { $0[NSPasteboard.PasteboardType.html.rawValue] }
            ?? items.map { $0.data(forType: .html) }
        let source = readDeclaredSource(from: items)
        let resultStamp = observation
        guard resultStamp.changeCount == stamp.changeCount, accessBehavior != .alwaysDeny else { return nil }
        if text == nil && (types?.contains(.string) == true || (types == nil && accessBehavior == .ask)) {
            failedAttempt = resultStamp
            readFailed = true
            SystemDiagnostics.clipboard(policy: accessBehavior, readFailed: true)
            return nil
        }
        let snapshot = Snapshot(
            stamp: resultStamp, text: text, richText: richText, sourceURI: sourceURI,
            chromiumSourceURL: chromiumSourceURL, htmlByItem: htmlByItem, source: source,
            hasSourceDeclaration: types?.contains(Self.sourceBundleType) == true,
            shouldExcludeFromHistory: !Self.historyExcludedTypes.isDisjoint(with: types ?? [])
        )
        cached = snapshot
        failedAttempt = nil
        readFailed = false
        return snapshot
    }

    func readForHistory(changeCount: Int) async -> Snapshot? {
        guard var snapshot = read(), snapshot.stamp.changeCount == changeCount else { return nil }
        guard !snapshot.shouldExcludeFromHistory, !snapshot.hasSourceDeclaration, snapshot.source == nil,
              let text = snapshot.text, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              let readSelection else { return snapshot }

        guard let images = ClipboardImages.read(htmlByItem: snapshot.htmlByItem, sourceURI: snapshot.sourceURI)
        else { return snapshot }
        let selection = await readSelection(changeCount, images.pageURL)
        let latestStamp = observation
        guard latestStamp.accessRevision == snapshot.stamp.accessRevision else { return nil }
        if latestStamp.changeCount == changeCount, let selection,
           let selectionText = images.textForComparison(selection),
           Self.selectionMatches(selectionText, source: selection, text: text, chromiumSourceURL: snapshot.chromiumSourceURL) {
            snapshot.source = selection.source
        }
        return snapshot
    }

    private static func selectionMatches(
        _ selectionText: String, source selection: Selection, text: String, chromiumSourceURL: URL?
    ) -> Bool {
        if selectionText.utf8.elementsEqual(text.utf8) { return true }
        guard selection.source.bundleID == chromeBundleID, let chromiumSourceURL,
              chromiumSourceURL.scheme != nil, selection.webPageURL == chromiumSourceURL else { return false }

        let lines = text.split(whereSeparator: \.isNewline)
            .map { $0.split(whereSeparator: \.isWhitespace).joined(separator: " ") }
            .filter { !$0.isEmpty }
        guard lines.count > 1 else { return false }
        var remaining = selectionText.split(whereSeparator: \.isWhitespace).joined(separator: " ").unicodeScalars[...]
        let listMarkers = ["• ", "◦ ", "▪ "]
        var previousLineEndsInNumber = false
        for line in lines {
            // Chrome can omit paragraph breaks and insert list markers at the start of a copied line.
            // Keep a separating boundary when two numeric fragments would otherwise run together.
            if previousLineEndsInNumber, remaining.first?.properties.numericType != nil { return false }
            if remaining.first == " " { remaining = remaining.dropFirst() }
            if !remaining.starts(with: line.unicodeScalars),
               let marker = listMarkers.first(where: { remaining.starts(with: $0.unicodeScalars) }) {
                remaining = remaining.dropFirst(marker.unicodeScalars.count)
            }
            guard remaining.starts(with: line.unicodeScalars) else { return false }
            remaining = remaining.dropFirst(line.unicodeScalars.count)
            previousLineEndsInNumber = line.unicodeScalars.last?.properties.numericType != nil
        }
        return remaining.isEmpty
    }

    private static func readForegroundSelection(changeCount: Int, imagePageURL: URL?) async -> Selection? {
        let tracker = LastActiveAppTracker.shared
        guard AXIsProcessTrusted(), let app = tracker.foregroundApp(forClipboardChange: changeCount),
              app.processIdentifier != NSRunningApplication.current.processIdentifier else { return nil }
        let processID = app.processIdentifier
        let readsPageURL = imagePageURL != nil || app.bundleIdentifier == chromeBundleID
        let selected = await Task.detached(priority: .utility) {
            selectedTextAndWindow(for: processID, readsPageURL: readsPageURL, imagePageURL: imagePageURL)
        }.value
        guard let selected, tracker.foregroundApp(forClipboardChange: changeCount)?.processIdentifier == processID
        else { return nil }

        let source = Source(
            name: app.localizedName, bundleID: app.bundleIdentifier, processID: processID, windowTitle: selected.title
        )
        return Selection(
            text: selected.text, source: source, webPageURL: selected.webPageURL, imageURLs: selected.imageURLs
        )
    }

    private nonisolated static func selectedTextAndWindow(
        for processID: pid_t,
        readsPageURL: Bool,
        imagePageURL: URL?
    ) -> FocusedSelection? {
        let app = AXUIElementCreateApplication(processID)
        AXUIElementSetMessagingTimeout(app, 0.10)
        let window = accessibilityElement(kAXFocusedWindowAttribute, on: app)
        guard let focused = accessibilityElement(kAXFocusedUIElementAttribute, on: app) else { return nil }
        let title = window.flatMap { accessibilityValue(kAXTitleAttribute, on: $0) as? String }
        let webPageURL: URL? = if readsPageURL, accessibilityValue(kAXRoleAttribute, on: focused) as? String == "AXWebArea" {
            accessibilityValue(kAXURLAttribute, on: focused) as? URL
        } else {
            nil
        }
        let text: String
        var selectedImageURLs: [URL]?
        if let imagePageURL {
            guard webPageURL == imagePageURL, let selected = selectedRange(on: focused),
                  let string = accessibilityParameter("AXStringForTextMarkerRange", on: focused, with: selected) as? String,
                  let urls = imageURLs(in: selected, on: focused) else { return nil }
            text = string
            selectedImageURLs = urls
        } else {
            guard let string = selectedText(on: focused) else { return nil }
            text = string
        }
        guard window == accessibilityElement(kAXFocusedWindowAttribute, on: app),
              focused == accessibilityElement(kAXFocusedUIElementAttribute, on: app) else { return nil }
        return FocusedSelection(
            text: text, title: title.flatMap { $0.isEmpty ? nil : $0 },
            webPageURL: webPageURL, imageURLs: selectedImageURLs
        )
    }

    private nonisolated static func selectedText(on element: AXUIElement) -> String? {
        if let text = accessibilityValue(kAXSelectedTextAttribute, on: element) as? String, !text.isEmpty {
            return text
        }
        // Safari can expose web content selection through the SDK's text marker attributes.
        guard let range = selectedRange(on: element) else { return nil }
        return accessibilityParameter("AXStringForTextMarkerRange", on: element, with: range) as? String
    }

    private nonisolated static func accessibilityElement(_ attribute: String, on element: AXUIElement) -> AXUIElement? {
        accessibilityElement(accessibilityValue(attribute, on: element))
    }

    private nonisolated static func accessibilityElement(_ value: CFTypeRef?) -> AXUIElement? {
        guard let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        let result = unsafeDowncast(value, to: AXUIElement.self)
        AXUIElementSetMessagingTimeout(result, 0.10)
        return result
    }

    private nonisolated static func accessibilityValue(_ attribute: String, on element: AXUIElement) -> CFTypeRef? {
        var value: CFTypeRef?
        return AXUIElementCopyAttributeValue(element, attribute as CFString, &value) == .success ? value : nil
    }

    private func readDeclaredSource(from items: [NSPasteboardItem]) -> Source? {
        let bundleIDs = items.filter { $0.types.contains(Self.sourceBundleType) }.map {
            ($0.string(forType: Self.sourceBundleType) ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        }
        guard let bundleID = bundleIDs.first, !bundleID.isEmpty,
              bundleIDs.dropFirst().allSatisfy({ $0 == bundleID }) else { return nil }
        let name = NSRunningApplication.runningApplications(withBundleIdentifier: bundleID).first?.localizedName
            ?? NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID)?.deletingPathExtension()
                .lastPathComponent
        return Source(name: name, bundleID: bundleID, processID: nil, windowTitle: nil)
    }

    private func readCommonSourceURI(from items: [NSPasteboardItem]) -> String? {
        // AppKit joins the text of all contributing items into a single history entry.
        let textItems = items.filter { $0.types.contains(.string) }
        guard let first = textItems.first, let uri = readSourceURI(from: first),
              textItems.dropFirst().allSatisfy({ readSourceURI(from: $0) == uri }) else { return nil }
        return uri
    }

    private func readSourceURI(from item: NSPasteboardItem) -> String? {
        let types = item.types
        if types.contains(Self.chromiumSourceType),
           let uri = item.string(forType: Self.chromiumSourceType),
           Self.isAbsoluteURI(uri) {
            return uri
        }

        for type in Self.webArchiveTypes where types.contains(type) {
            if let data = item.data(forType: type),
               let archive = try? PropertyListDecoder().decode(WebArchive.self, from: data),
               Self.isAbsoluteURI(archive.mainResource.uri) {
                return archive.mainResource.uri
            }
        }
        return nil
    }

    private static func isAbsoluteURI(_ value: String) -> Bool {
        URL(string: value, encodingInvalidCharacters: false)?.scheme != nil
    }

    private struct WebArchive: Decodable {
        struct Resource: Decodable {
            let uri: String

            enum CodingKeys: String, CodingKey {
                case uri = "WebResourceURL"
            }
        }

        let mainResource: Resource

        enum CodingKeys: String, CodingKey {
            case mainResource = "WebMainResource"
        }
    }

    private func invalidate() {
        accessRevision &+= 1
        cached = nil
        failedAttempt = nil
        readFailed = false
    }
}

private extension ClipboardReader {
    nonisolated static func accessibilityParameter(
        _ attribute: String, on element: AXUIElement, with input: CFTypeRef
    ) -> CFTypeRef? {
        var result: CFTypeRef?
        let status = AXUIElementCopyParameterizedAttributeValue(element, attribute as CFString, input, &result)
        return status == .success ? result : nil
    }

    nonisolated static func markerRange(_ value: CFTypeRef?) -> AXTextMarkerRange? {
        guard let value, CFGetTypeID(value) == AXTextMarkerRangeGetTypeID() else { return nil }
        return unsafeDowncast(value, to: AXTextMarkerRange.self)
    }

    nonisolated static func selectedRange(on element: AXUIElement) -> AXTextMarkerRange? {
        markerRange(accessibilityValue("AXSelectedTextMarkerRange", on: element))
    }

    nonisolated static func precedes(_ lhs: AXTextMarker, _ rhs: AXTextMarker, on web: AXUIElement) -> Bool? {
        if CFEqual(lhs, rhs) { return false }
        let input = [lhs, rhs] as CFArray
        guard let ordered = markerRange(accessibilityParameter("AXTextMarkerRangeForUnorderedTextMarkers", on: web, with: input))
        else { return nil }
        let start = AXTextMarkerRangeCopyStartMarker(ordered)
        let end = AXTextMarkerRangeCopyEndMarker(ordered)
        if CFEqual(start, lhs), CFEqual(end, rhs) { return true }
        return CFEqual(start, rhs) && CFEqual(end, lhs) ? false : nil
    }

    nonisolated static func imageURLs(in range: AXTextMarkerRange, on web: AXUIElement) -> [URL]? {
        let start = AXTextMarkerRangeCopyStartMarker(range)
        let end = AXTextMarkerRangeCopyEndMarker(range)
        guard precedes(start, end, on: web) == true else { return nil }
        let deadline = ProcessInfo.processInfo.systemUptime + 0.35
        var pending = [selectionContainer(from: start, to: end, on: web)]
        var inspected = 0
        var previousImage: AXTextMarker?
        var urls: [URL] = []

        while let node = pending.popLast() {
            guard inspected < 512, ProcessInfo.processInfo.systemUptime < deadline,
                  let role = accessibilityValue(kAXRoleAttribute, on: node) as? String else { return nil }
            inspected += 1
            if role == kAXImageRole {
                let value = accessibilityParameter("AXTextMarkerRangeForUIElement", on: web, with: node)
                guard let imageRange = markerRange(value) else { return nil }
                let first = AXTextMarkerRangeCopyStartMarker(imageRange)
                let last = AXTextMarkerRangeCopyEndMarker(imageRange)
                guard let afterStart = precedes(start, first, on: web),
                      let beforeEnd = precedes(last, end, on: web) else { return nil }
                if afterStart && beforeEnd {
                    let owner = accessibilityParameter("AXUIElementForTextMarker", on: web, with: first)
                    guard accessibilityElement(owner) == node,
                          let url = accessibilityValue(kAXURLAttribute, on: node) as? URL, url.scheme != nil,
                          previousImage.map({ precedes($0, first, on: web) == true }) ?? true else { return nil }
                    urls.append(url)
                    previousImage = first
                }
            }
            guard let children = accessibilityChildren(of: node) else { return nil }
            pending.append(contentsOf: children.reversed())
        }
        guard let current = selectedRange(on: web),
              CFEqual(start, AXTextMarkerRangeCopyStartMarker(current)),
              CFEqual(end, AXTextMarkerRangeCopyEndMarker(current)) else { return nil }
        return urls
    }

    nonisolated static func accessibilityChildren(of node: AXUIElement) -> [AXUIElement]? {
        var value: CFTypeRef?
        let status = AXUIElementCopyAttributeValue(node, kAXChildrenAttribute as CFString, &value)
        if status == .noValue || status == .attributeUnsupported { return [] }
        guard status == .success, let values = value as? [AnyObject] else { return nil }
        let children = values.compactMap { accessibilityElement($0) }
        return children.count == values.count ? children : nil
    }

    nonisolated static func selectionContainer(from start: AXTextMarker, to end: AXTextMarker, on web: AXUIElement) -> AXUIElement {
        // Start with the parent so an image between two text positions can be visited.
        let startParents = selectionAncestors(of: start, on: web).dropFirst()
        let endParents = selectionAncestors(of: end, on: web).dropFirst()
        let commonParent = startParents.first { endParents.contains($0) }
        return commonParent ?? web
    }

    nonisolated static func selectionAncestors(of marker: AXTextMarker, on web: AXUIElement) -> [AXUIElement] {
        var element = accessibilityElement(accessibilityParameter("AXUIElementForTextMarker", on: web, with: marker))
        var ancestors: [AXUIElement] = []
        while let node = element, ancestors.count < 20 {
            ancestors.append(node)
            if node == web { return ancestors }
            element = accessibilityElement(kAXParentAttribute, on: node)
        }
        return []
    }
}

private struct ClipboardImages {
    private static let objectReplacement: Unicode.Scalar = "\u{FFFC}"

    let pageURL: URL?
    private let urls: [String]
    private let alternatives: [String]

    // A nil result means image identity could not be established from the clipboard data.
    static func read(htmlByItem: [Data?], sourceURI: String?) -> Self? {
        var images: [HTMLImage] = []
        let fragments = htmlByItem.compactMap { $0 }
        for data in fragments {
            guard let parsed = HTMLImage.read(from: data) else { return nil }
            images.append(contentsOf: parsed)
        }
        if images.isEmpty { return Self(pageURL: nil, urls: [], alternatives: []) }

        guard htmlByItem.count == 1, let sourceURI,
              let pageURL = URL(string: sourceURI, encodingInvalidCharacters: false),
              pageURL.scheme != nil else { return nil }
        let urls = images.compactMap { URL(string: $0.source, relativeTo: pageURL)?.absoluteURL.absoluteString }
        guard urls.count == images.count else { return nil }
        return Self(pageURL: pageURL, urls: urls, alternatives: images.map(\.alternative))
    }

    func textForComparison(_ selection: ClipboardReader.Selection) -> String? {
        let parts = selection.text.unicodeScalars.split(separator: Self.objectReplacement, omittingEmptySubsequences: false)
        if urls.isEmpty {
            return parts.count == 1 ? selection.text : nil
        }
        guard selection.webPageURL == pageURL,
              selection.imageURLs?.map(\.absoluteString) == urls,
              parts.count == alternatives.count + 1, let first = parts.first else { return nil }
        var text = String(first)
        for (alternative, suffix) in zip(alternatives, parts.dropFirst()) {
            text += alternative
            text += String(suffix)
        }
        return text
    }

    private struct HTMLImage {
        let source: String
        let alternative: String

        static func read(from data: Data) -> [Self]? {
            if data.isEmpty { return [] }
            guard data.count <= 1_048_576 else { return nil }
            let options = Int32(HTML_PARSE_NONET.rawValue | HTML_PARSE_NOERROR.rawValue | HTML_PARSE_NOWARNING.rawValue)
            let document = data.withUnsafeBytes { bytes in
                htmlReadMemory(bytes.bindMemory(to: CChar.self).baseAddress, Int32(bytes.count), nil, "UTF-8", options)
            }
            guard let document else { return nil }
            defer { xmlFreeDoc(document) }
            guard let root = xmlDocGetRootElement(document) else { return nil }
            var pending = [root]
            var images: [Self] = []
            while let node = pending.popLast() {
                if let next = node.pointee.next { pending.append(next) }
                if let child = node.pointee.children { pending.append(child) }
                guard node.pointee.type == XML_ELEMENT_NODE, let name = node.pointee.name else { continue }
                switch String(cString: name) {
                case "base" where attribute("href", on: node) != nil, "picture":
                    return nil
                case "img":
                    guard let source = attribute("src", on: node), !source.isEmpty,
                          attribute("srcset", on: node) == nil else { return nil }
                    images.append(Self(source: source, alternative: attribute("alt", on: node) ?? ""))
                default:
                    break
                }
            }
            return images
        }

        private static func attribute(_ name: String, on node: xmlNodePtr) -> String? {
            guard let attribute = xmlHasProp(node, name) else { return nil }
            guard let value = attribute.pointee.children?.pointee.content else { return "" }
            return String(cString: value)
        }
    }
}
